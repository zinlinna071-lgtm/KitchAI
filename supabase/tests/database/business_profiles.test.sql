begin;
select plan(21);

insert into auth.users (id, aud, role, email, encrypted_password, email_confirmed_at)
values
  ('11111111-1111-4111-8111-111111111111', 'authenticated', 'authenticated', 'owner-a@example.test', '', now()),
  ('22222222-2222-4222-8222-222222222222', 'authenticated', 'authenticated', 'owner-b@example.test', '', now())
on conflict (id) do nothing;

select ok(
  (select relrowsecurity from pg_class where oid = 'public.business_profiles'::regclass),
  'row-level security is enabled'
);
select ok(not has_table_privilege('anon', 'public.business_profiles', 'select'), 'anonymous users cannot select profiles');
select ok(not has_table_privilege('anon', 'public.business_profiles', 'insert'), 'anonymous users cannot insert profiles');
select ok(not has_table_privilege('authenticated', 'public.business_profiles', 'delete'), 'authenticated users cannot delete profiles');

set local role authenticated;
set local "request.jwt.claim.sub" = '11111111-1111-4111-8111-111111111111';

select lives_ok(
  $$insert into public.business_profiles (id, owner_id, business_id, name, created_at, updated_at, revision)
    values ('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',
      '22222222-2222-4222-8222-222222222222',
      'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',
      '  Owner A Kitchen  ', '2000-01-01T00:00:00Z', '2000-01-01T00:00:00Z', 77)$$,
  'authenticated owner can create a profile'
);
select is(
  (select owner_id::text from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  '11111111-1111-4111-8111-111111111111',
  'owner_id is derived from authenticated identity, not client input'
);
select is(
  (select name from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  'Owner A Kitchen',
  'profile name is trimmed server-side'
);
select is(
  (select revision from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  1::bigint,
  'revision is initialized by the server'
);
select ok(
  (select business_id <> 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb'::uuid from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  'business_id is generated by the server'
);
select ok(
  (select created_at::date = current_date from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  'created_at is generated by the server'
);
select ok(
  (select updated_at::date = current_date from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  'updated_at is generated by the server'
);

select lives_ok(
  $$update public.business_profiles
    set owner_id = '22222222-2222-4222-8222-222222222222',
        business_id = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',
        created_at = '2000-01-01T00:00:00Z',
        revision = 99,
        name = 'Owner A Kitchen Updated'
    where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'$$,
  'owner can update editable profile fields'
);
select is(
  (select revision from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  2::bigint,
  'revision increments on update and ignores client-supplied revision'
);
select is(
  (select owner_id::text from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  '11111111-1111-4111-8111-111111111111',
  'owner_id cannot be changed by the client'
);
select ok(
  (select created_at::date = current_date from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  'created_at remains immutable after update'
);
select ok(
  (select business_id <> 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb'::uuid from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  'business_id remains immutable after update'
);

set local "request.jwt.claim.sub" = '22222222-2222-4222-8222-222222222222';
select is(
  (select count(*)::integer from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  0,
  'owner B cannot read owner A profile'
);
select lives_ok(
  $$update public.business_profiles set name = 'Unauthorized edit'
    where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'$$,
  'owner B update is safely filtered by row-level security'
);
set local "request.jwt.claim.sub" = '11111111-1111-4111-8111-111111111111';
select is(
  (select name from public.business_profiles where id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'),
  'Owner A Kitchen Updated',
  'owner B cannot modify owner A profile'
);

set local "request.jwt.claim.sub" = '22222222-2222-4222-8222-222222222222';
select lives_ok(
  $$insert into public.business_profiles (id, owner_id, name)
    values ('cccccccc-cccc-4ccc-8ccc-cccccccccccc',
      '11111111-1111-4111-8111-111111111111', 'Owner B Kitchen')$$,
  'owner B can create their own profile despite spoofed owner_id'
);
select is(
  (select owner_id::text from public.business_profiles where id = 'cccccccc-cccc-4ccc-8ccc-cccccccccccc'),
  '22222222-2222-4222-8222-222222222222',
  'owner B profile is bound to owner B identity'
);

reset role;
select * from finish();
rollback;
